"""Generate explicitly synthetic video + annotations for the evaluation CLI."""

import argparse
import json
from pathlib import Path

import cv2

from cascade_vision.cli import generate_synthetic_stream


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, default=Path("reports/fixture"))
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    video = args.output_dir / "synthetic.avi"
    writer = cv2.VideoWriter(str(video), cv2.VideoWriter_fourcc(*"MJPG"), 30, (640, 480))
    if not writer.isOpened():
        raise RuntimeError("MJPG VideoWriter is not available")
    try:
        for frame in generate_synthetic_stream():
            writer.write(frame)
    finally:
        writer.release()
    document = {
        "schema_version": 1,
        "event_labels": ["person", "backpack"],
        "clips": [
            {
                "id": "synthetic-demo",
                "path": video.name,
                "footage_type": "synthetic",
                "license": "Generated by cascade-vision under MIT; synthetic fixture, not real-video evidence",
                "events": [
                    {"id": "person-1", "label": "person", "start_s": 100 / 30, "end_s": 250 / 30},
                    {"id": "backpack-1", "label": "backpack", "start_s": 175 / 30, "end_s": 250 / 30},
                ],
            }
        ],
    }
    manifest = args.output_dir / "manifest.json"
    manifest.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(manifest)


if __name__ == "__main__":
    main()

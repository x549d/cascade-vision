"""Stage 2: YOLO + ByteTrack Multi-Object Tracker and Hard-Sample Cascade Router.

Implements :class:`VLMTask` and :class:`CascadeTracker` with:
- Persistent multi-object tracking via ``ultralytics.YOLO.track(..., persist=True, tracker="bytetrack.yaml")``
- Built-in static NumPy geometry helper :meth:`CascadeTracker.compute_iou`
- Three-trigger cascade state machine with per-track streak counting (``streak_count``)
  and anti-bounce cooldown (``last_audited_frame``):
    * ``FIRST_SEEN_PRIORITY``: target in ``priority_classes`` and ``stable detector observations >= min_stable_frames``
    * ``LOW_CONF_HARD_EXAMPLE``: confidence in ``[conf_min, conf_ambiguous_upper]``
    * ``OBJECT_INTERACTION``: two priority targets in the current frame have IoU > 0.35
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional, Sequence, Set, Tuple

import cv2
import numpy as np

from .config import CascadeConfig
from .motion import MotionGate

logger = logging.getLogger(__name__)


class TriggerReason(str, Enum):
    """Cascade trigger reasons for escalating a tracked target to Stage 3 VLM."""

    FIRST_SEEN_PRIORITY = "FIRST_SEEN_PRIORITY"
    LOW_CONF_HARD_EXAMPLE = "LOW_CONF_HARD_EXAMPLE"
    OBJECT_INTERACTION = "OBJECT_INTERACTION"

    # Backward-compatible aliases
    NEW_PRIORITY_TARGET = "FIRST_SEEN_PRIORITY"
    AMBIGUOUS_CONFIDENCE = "LOW_CONF_HARD_EXAMPLE"
    OCCLUSION_INTERACTION = "OBJECT_INTERACTION"


@dataclass
class VLMTask:
    """Task payload generated by Stage 2 for asynchronous Stage 3 VLM inspection."""

    frame_idx: int
    track_id: int
    yolo_class: str
    yolo_conf: float
    bbox: List[int]
    trigger_reason: str
    roi_b64: str = ""
    partner_track_id: Optional[int] = None

    @property
    def class_name(self) -> str:
        """Alias for ``yolo_class``."""
        return self.yolo_class

    @property
    def confidence(self) -> float:
        """Alias for ``yolo_conf``."""
        return self.yolo_conf

    @property
    def roi_base64(self) -> str:
        """Alias for ``roi_b64``."""
        return self.roi_b64

    @roi_base64.setter
    def roi_base64(self, value: str) -> None:
        self.roi_b64 = value


@dataclass
class TrackedObject:
    """Structured representation of a single tracked target in the current frame."""

    track_id: int
    yolo_class: str
    yolo_conf: float
    bbox: List[int]
    streak_count: int = 1
    trigger_reason: Optional[str] = None

    @property
    def class_name(self) -> str:
        return self.yolo_class

    @property
    def confidence(self) -> float:
        return self.yolo_conf

    @property
    def stable_frames(self) -> int:
        return self.streak_count

    def to_dict(self) -> Dict[str, Any]:
        return {
            "track_id": self.track_id,
            "yolo_class": self.yolo_class,
            "yolo_conf": self.yolo_conf,
            "bbox": list(self.bbox),
            "streak_count": self.streak_count,
            "trigger_reason": self.trigger_reason,
        }


@dataclass
class Stage2Result:
    """Aggregate wrapper for Stage 2 frame output (unpackable as ``(detections, vlm_tasks)``)."""

    frame_idx: int
    tracked_objects: List[TrackedObject] = field(default_factory=list)
    vlm_tasks: List[VLMTask] = field(default_factory=list)

    def __iter__(self):
        yield self.tracked_objects
        yield self.vlm_tasks


class _FallbackContourTracker:
    """Lightweight HSV contour + IoU tracker used when ``ultralytics`` is not installed
    or when synthetic OpenCV demo frames are evaluated offline.
    """

    def __init__(self, conf_min: float = 0.25) -> None:
        self.conf_min = conf_min
        self._tracks: Dict[int, Tuple[List[int], str, int]] = {}
        self._next_id: int = 1
        self._tick: int = 0

    def reset(self) -> None:
        self._tracks.clear()
        self._next_id = 1
        self._tick = 0

    def track(self, frame: np.ndarray) -> List[Tuple[int, str, float, List[int]]]:
        self._tick += 1
        self._tracks = {tid: data for tid, data in self._tracks.items() if self._tick - data[2] <= 15}
        hsv = cv2.cvtColor(frame, cv2.COLOR_BGR2HSV)
        sat_mask = cv2.inRange(hsv, (0, 75, 70), (180, 255, 255))
        kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (5, 5))
        sat_mask = cv2.morphologyEx(sat_mask, cv2.MORPH_CLOSE, kernel)

        contours_info = cv2.findContours(sat_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        contours = contours_info[0] if len(contours_info) == 2 else contours_info[1]

        raw_dets: List[Tuple[List[int], str, float]] = []
        for cnt in contours:
            if cv2.contourArea(cnt) < 250:
                continue
            x, y, w, h = cv2.boundingRect(cnt)
            bbox = [int(x), int(y), int(x + w), int(y + h)]
            roi_hsv = hsv[y : y + h, x : x + w]
            mean_h = float(np.mean(roi_hsv[..., 0]))
            aspect = h / float(max(1, w))
            if (mean_h < 15 or mean_h > 160) and aspect >= 1.2:
                cls_name, conf = "person", 0.86
            elif 18 <= mean_h < 40:
                cls_name, conf = "backpack", 0.42
            elif 90 <= mean_h <= 135:
                cls_name, conf = "car", 0.89
            elif 40 <= mean_h < 90:
                cls_name, conf = "suitcase", 0.48
            else:
                cls_name, conf = "person", 0.50
            if conf >= self.conf_min:
                raw_dets.append((bbox, cls_name, conf))

        results: List[Tuple[int, str, float, List[int]]] = []
        used_tracks: Set[int] = set()
        for bbox, cls_name, conf in raw_dets:
            best_tid: Optional[int] = None
            best_iou = 0.25
            for tid, (prev_box, _prev_cls, last_tick) in self._tracks.items():
                if tid in used_tracks or (self._tick - last_tick) > 15:
                    continue
                iou_val = CascadeTracker.compute_iou(bbox, prev_box)
                if iou_val > best_iou:
                    best_iou = iou_val
                    best_tid = tid
            if best_tid is None:
                best_tid = self._next_id
                self._next_id += 1
            used_tracks.add(best_tid)
            self._tracks[best_tid] = (bbox, cls_name, self._tick)
            results.append((best_tid, cls_name, conf, bbox))

        return results


class CascadeTracker:
    """Stage 2 YOLO + ByteTrack multi-object tracker and hard-sample cascade router."""

    def __init__(
        self,
        config: Optional[CascadeConfig] = None,
        model: Optional[Any] = None,
        use_fallback_if_unavailable: bool = False,
    ) -> None:
        self.config = config or CascadeConfig()
        self.priority_set: Set[str] = {c.lower().strip() for c in self.config.priority_classes}

        # Per-track state machine counters:
        # streak_count: track_id -> consecutive detector evaluations containing the track
        self.streak_count: Dict[int, int] = {}
        # last_audited_frame: track_id -> last frame_idx when a VLMTask was triggered
        self.last_audited_frame: Dict[int, int] = {}
        self._last_seen_frame: Dict[int, int] = {}
        self._evaluation_idx = 0
        self._last_evaluation: Dict[int, int] = {}

        # Backward-compatible aliases pointing to the same underlying dicts
        self.track_FirstSeen = self.streak_count
        self.inspected_tracks = self.last_audited_frame

        self._fallback_tracker = _FallbackContourTracker(conf_min=self.config.conf_min)
        self.model: Optional[Any] = model
        self._use_fallback = False

        if self.model is None:
            if str(self.config.yolo_model).lower() in {"mock", "fallback", "synthetic"}:
                self._use_fallback = True
            else:
                try:
                    from ultralytics import YOLO

                    self.model = YOLO(self.config.yolo_model)
                except Exception as exc:
                    if use_fallback_if_unavailable:
                        logger.warning(
                            "Could not load ultralytics YOLO model '%s' (%s); using built-in fallback tracker.",
                            self.config.yolo_model,
                            exc,
                        )
                        self._use_fallback = True
                    else:
                        raise

    def reset(self) -> None:
        """Reset all per-track streak counters and cooldown states."""
        self.streak_count.clear()
        self.last_audited_frame.clear()
        self._last_seen_frame.clear()
        self._last_evaluation.clear()
        self._evaluation_idx = 0
        self._fallback_tracker.reset()

    @staticmethod
    def compute_iou(box_a: Sequence[float], box_b: Sequence[float]) -> float:
        """Compute Intersection over Union (IoU) between two ``[x1, y1, x2, y2]`` boxes."""
        a = np.asarray(box_a, dtype=np.float64).ravel()
        b = np.asarray(box_b, dtype=np.float64).ravel()
        if a.size != 4 or b.size != 4:
            raise ValueError("compute_iou expects two 4-element boxes [x1, y1, x2, y2]")

        ax1, ay1 = float(min(a[0], a[2])), float(min(a[1], a[3]))
        ax2, ay2 = float(max(a[0], a[2])), float(max(a[1], a[3]))
        bx1, by1 = float(min(b[0], b[2])), float(min(b[1], b[3]))
        bx2, by2 = float(max(b[0], b[2])), float(max(b[1], b[3]))

        inter_x1 = max(ax1, bx1)
        inter_y1 = max(ay1, by1)
        inter_x2 = min(ax2, bx2)
        inter_y2 = min(ay2, by2)

        inter_w = max(0.0, inter_x2 - inter_x1)
        inter_h = max(0.0, inter_y2 - inter_y1)
        inter_area = inter_w * inter_h
        if inter_area <= 0.0:
            return 0.0

        area_a = max(0.0, ax2 - ax1) * max(0.0, ay2 - ay1)
        area_b = max(0.0, bx2 - bx1) * max(0.0, by2 - by1)
        union_area = area_a + area_b - inter_area
        if union_area <= 0.0:
            return 0.0
        return float(inter_area / union_area)

    def _is_cooled_down(self, track_id: int, frame_idx: int) -> bool:
        """Return ``True`` if ``track_id`` has never been audited or cooldown has elapsed."""
        if track_id not in self.last_audited_frame:
            return True
        return (frame_idx - self.last_audited_frame[track_id]) >= self.config.cooldown_frames

    def _extract_raw_tracks(self, frame: np.ndarray) -> List[Tuple[int, str, float, List[int]]]:
        """Execute ``self.model.track(...)`` with ByteTrack and parse bounding boxes."""
        if self._use_fallback or self.model is None:
            return self._fallback_tracker.track(frame)

        results = self.model.track(
            frame,
            persist=True,
            conf=self.config.conf_min,
            tracker="bytetrack.yaml",
            verbose=False,
        )
        if not results:
            return []

        res = results[0]
        boxes = getattr(res, "boxes", None)
        if boxes is None or len(boxes) == 0:
            return []

        xyxy = boxes.xyxy.cpu().numpy() if hasattr(boxes.xyxy, "cpu") else np.asarray(boxes.xyxy)
        confs = boxes.conf.cpu().numpy() if hasattr(boxes.conf, "cpu") else np.asarray(boxes.conf)
        clss = boxes.cls.cpu().numpy().astype(int) if hasattr(boxes.cls, "cpu") else np.asarray(boxes.cls, dtype=int)
        if getattr(boxes, "id", None) is not None:
            ids_arr = (
                boxes.id.cpu().numpy().astype(int) if hasattr(boxes.id, "cpu") else np.asarray(boxes.id, dtype=int)
            )
            track_ids = [int(i) for i in ids_arr.tolist()]
        else:
            track_ids = list(range(1, len(xyxy) + 1))

        names_map = getattr(res, "names", None) or getattr(self.model, "names", {}) or {}
        extracted: List[Tuple[int, str, float, List[int]]] = []
        for tid, box, conf, cls_id in zip(track_ids, xyxy, confs, clss):
            if float(conf) < self.config.conf_min:
                continue
            cls_name = str(names_map.get(int(cls_id), cls_id))
            int_bbox = [int(round(float(v))) for v in box[:4]]
            extracted.append((int(tid), cls_name, float(conf), int_bbox))

        return extracted

    def evaluate_detections(
        self,
        raw_detections: Sequence[Tuple[int, str, float, Sequence[float]]],
        frame_idx: int,
        frame: Optional[np.ndarray] = None,
    ) -> Stage2Result:
        """Run the three-rule cascade state machine over tracked detections for ``frame_idx``.

        Trigger rules (evaluated only when ``_is_cooled_down(track_id, frame_idx)`` is True):
        - Condition A (``FIRST_SEEN_PRIORITY``): ``yolo_class`` in ``priority_classes``
          and ``stable detector observations >= min_stable_frames``.
        - Condition B (``LOW_CONF_HARD_EXAMPLE``): ``conf_min <= yolo_conf <= conf_ambiguous_upper``.
        - Condition C (``OBJECT_INTERACTION``): IoU > 0.35 between two ``priority_classes``
          targets in the current frame.
        """
        active_ids: Set[int] = set()
        tracked_objects: List[TrackedObject] = []

        # Count consecutive detector evaluations, allowing Stage 1 to skip raw frames.
        self._evaluation_idx += 1
        for tid, last_seen in list(self._last_seen_frame.items()):
            if frame_idx - last_seen > self.config.max_track_age_frames:
                self._last_seen_frame.pop(tid, None)
                self._last_evaluation.pop(tid, None)
                self.streak_count.pop(tid, None)
                self.last_audited_frame.pop(tid, None)
        for tid, cls_name, conf, bbox in raw_detections:
            active_ids.add(tid)
            if self._last_evaluation.get(tid) == self._evaluation_idx - 1:
                self.streak_count[tid] = self.streak_count.get(tid, 0) + 1
            else:
                self.streak_count[tid] = 1
            self._last_seen_frame[tid] = frame_idx
            self._last_evaluation[tid] = self._evaluation_idx

            int_bbox = [int(round(float(v))) for v in bbox[:4]]
            tracked_objects.append(
                TrackedObject(
                    track_id=int(tid),
                    yolo_class=str(cls_name),
                    yolo_conf=float(conf),
                    bbox=int_bbox,
                    streak_count=self.streak_count[tid],
                )
            )

        # Reset streak_count for tracks that disappeared in this frame
        for tid in list(self.streak_count.keys()):
            if tid not in active_ids and self._last_seen_frame.get(tid, frame_idx) < frame_idx:
                self.streak_count[tid] = 0

        # 2. Detect pairwise OBJECT_INTERACTION (IoU > 0.35) among priority targets
        interaction_partners: Dict[int, int] = {}
        priority_targets = [obj for obj in tracked_objects if obj.yolo_class.lower() in self.priority_set]
        for i in range(len(priority_targets)):
            for j in range(i + 1, len(priority_targets)):
                obj_a, obj_b = priority_targets[i], priority_targets[j]
                if self.compute_iou(obj_a.bbox, obj_b.bbox) > self.config.occlusion_iou_threshold:
                    interaction_partners.setdefault(obj_a.track_id, obj_b.track_id)
                    interaction_partners.setdefault(obj_b.track_id, obj_a.track_id)

        # 3. Evaluate Conditions A, B, C with anti-bounce cooldown
        vlm_tasks: List[VLMTask] = []
        for obj in tracked_objects:
            if not self._is_cooled_down(obj.track_id, frame_idx):
                continue

            is_priority = obj.yolo_class.lower() in self.priority_set
            reason: Optional[TriggerReason] = None
            partner_id: Optional[int] = None

            # Condition A: FIRST_SEEN_PRIORITY (priority class + stable detector observations >= min_stable_frames)
            if (
                is_priority
                and obj.streak_count >= self.config.min_stable_frames
                and obj.track_id not in self.last_audited_frame
            ):
                reason = TriggerReason.FIRST_SEEN_PRIORITY

            # Condition B: LOW_CONF_HARD_EXAMPLE (conf in [conf_min, conf_ambiguous_upper])
            elif self.config.conf_min <= obj.yolo_conf <= self.config.conf_ambiguous_upper:
                reason = TriggerReason.LOW_CONF_HARD_EXAMPLE

            # Condition C: OBJECT_INTERACTION (two priority targets with IoU > 0.35)
            elif obj.track_id in interaction_partners:
                reason = TriggerReason.OBJECT_INTERACTION
                partner_id = interaction_partners[obj.track_id]

            if reason is not None:
                obj.trigger_reason = reason.value
                self.last_audited_frame[obj.track_id] = frame_idx
                roi_b64 = ""
                if frame is not None and frame.size > 0:
                    roi_b64 = MotionGate.encode_roi_base64(
                        frame,
                        obj.bbox,
                        padding_ratio=self.config.roi_padding_ratio,
                        jpeg_quality=self.config.jpeg_quality,
                    )
                vlm_tasks.append(
                    VLMTask(
                        frame_idx=frame_idx,
                        track_id=obj.track_id,
                        yolo_class=obj.yolo_class,
                        yolo_conf=obj.yolo_conf,
                        bbox=list(obj.bbox),
                        trigger_reason=reason.value,
                        roi_b64=roi_b64,
                        partner_track_id=partner_id,
                    )
                )

        return Stage2Result(
            frame_idx=frame_idx,
            tracked_objects=tracked_objects,
            vlm_tasks=vlm_tasks,
        )

    def process_frame(self, frame: np.ndarray, frame_idx: int) -> Tuple[List[TrackedObject], List[VLMTask]]:
        """Run YOLO + ByteTrack on ``frame`` and return ``(detections, vlm_tasks)``."""
        raw_detections = self._extract_raw_tracks(frame)
        result = self.evaluate_detections(raw_detections, frame_idx=frame_idx, frame=frame)
        return result.tracked_objects, result.vlm_tasks


compute_iou = CascadeTracker.compute_iou
